Graphics::Surface *blendToSurface(const Common::Array<byte> &pixels, int w, int h) {
	if (w <= 0 || h <= 0 || (int)pixels.size() < w * h)
		return nullptr;

	// Match the exact format produced by loadSurfaceRGBA():
	// Graphics::PixelFormat rgba(4, 8, 8, 8, 8, 24, 16, 8, 0)
	const Graphics::PixelFormat fmt(4, 8, 8, 8, 8, 24, 16, 8, 0);

	Graphics::Surface *out = new Graphics::Surface();
	out->create(w, h, fmt);

	for (int y = 0; y < h; y++) {
		for (int x = 0; x < w; x++) {
			uint32 v = BLEND_TABLE[pixels[y * w + x]];
			uint8 r = (uint8)(v & 0xff);
			uint8 g = (uint8)((v >> 8) & 0xff);
			uint8 b = (uint8)((v >> 16) & 0xff);
			out->setPixel(x, y, fmt.RGBToColor(r, g, b));
		}
	}

	return out;
}

